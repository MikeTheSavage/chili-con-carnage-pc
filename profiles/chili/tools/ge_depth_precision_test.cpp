static void require(bool r,const std::string &message){if(!r)throw std::runtime_error(message);}
static float reg(float v){return chili::ge_float24_register(std::bit_cast<unsigned>(v)>>8);}
static float projection(float z,float coefficient,float translation){float out;std::string error;
    require(chili::ge_float24_projection_z(z,reg(coefficient),reg(translation),out,error),error);return out;}
static chili::GeDepthSample depth(float z,float w,float scale,float center,bool clamp=false,unsigned min=0,unsigned max=65535){
    chili::GeDepthSample out;std::string error;
    require(chili::ge_depth_verified(z,w,reg(scale),reg(center),min,max,clamp,out,error),error);return out;}
static constexpr unsigned viewport_k[]={1,2,3,100,1001,16381,20000,32760};
static constexpr unsigned offset_k[]={500,1100,1600,2100,3000,5000,9000,40000};
static constexpr unsigned w1_expected[]={0,1024,1024,2048,2048,4096,8192,39936};
static constexpr unsigned w3_expected[]={4660,4660,0,0,1024,3072,7168,37888};
static void hardware_vectors(){
    require(reg(131071)==131070 && reg(-131071)==-131070,"16-significant-bit register decode mismatch");
    // Exact primary real-PSP expected vectors, not values generated by this
    // implementation. Inputs are built exactly as transformprecision.cpp.
    for(unsigned k:viewport_k){const auto out=depth(0.5f+k/65536.0f,1,131071,-65535);
        require(out.range_pass&&out.depth==2*k,"hardware viewport cancellation mismatch k="+std::to_string(k));}
    for(unsigned i=0;i<8;++i){const unsigned k=offset_k[i];
        const auto one=depth(projection(k/67108864.0f,1,.75f),1,65535.0f*1024,-.75f*65535*1024);
        require(one.range_pass&&one.depth==w1_expected[i],"hardware W=1 offset mismatch k="+std::to_string(k));
        const auto three=depth(projection(k/67108864.0f,3,2.25f),3,65535.0f*1024,-.75f*65535*1024);
        unsigned stored=4660;if(three.range_pass)stored=three.depth;
        require(stored==w3_expected[i]&&(three.range_pass==(i>=2)),"hardware W=3 offset/range mismatch k="+std::to_string(k));
        if(i<2)require(three.screen_z==-1024,"W=3 failed range was hidden instead of represented");}
    // depth/precision.expected establishes 4660 baseline, 4659 at center
    // 32767, and 4661 at center 32768 with signed-16 position /32768.
    const float source_z=float(0x6DCC)/32768.0f;
    const unsigned expected[]={4659,4660,4661};const float centers[]={32767,32767.5f,32768};
    for(unsigned i=0;i<3;++i){const auto out=depth(source_z,1,-32767.5f,centers[i]);
        require(out.range_pass&&out.depth==expected[i],"hardware depth/precision center mismatch");}
}
static void derived_reciprocal_constraint(){
    // An independent exhaustive endpoint constraint: scan ALL float24 values
    // in [0.25,0.5), not only values near mathematical 1/3. Only the empirical
    // endpoint may satisfy these eight recorded depths under verified stages.
    unsigned matches=0,matched=0;std::string error;
    std::array<float,8> clips;for(unsigned i=0;i<8;++i)clips[i]=projection(offset_k[i]/67108864.0f,3,2.25f);
    for(unsigned bits=0x3E800000;bits<0x3F000000;bits+=256){bool match=true;
        for(unsigned i=0;i<8&&match;++i){chili::GeDepthSample out;
            require(chili::ge_depth_with_reciprocal(clips[i],std::bit_cast<float>(bits),reg(65535.0f*1024),
                reg(-.75f*65535*1024),0,65535,false,out,error),error);
            const unsigned stored=out.range_pass?out.depth:4660;
            match=stored==w3_expected[i]&&(out.range_pass==(i>=2));}
        if(match){++matches;matched=bits;}}
    require(matches==1&&matched==0x3EAAAA00,"W=3 reciprocal endpoint was guessed/non-unique");
}
static void arithmetic_and_failures(){
    std::string error;float out=999;
    require(chili::ge_float24_add(65536,-65535,out,error)&&out==2,"positive cancellation ignored aligned operand truncation");
    require(chili::ge_float24_add(-65536,65535,out,error)&&out==-2,"negative cancellation ignored aligned operand truncation");
    for(unsigned k:viewport_k){const auto mirror=depth(.5f+k/65536.0f,1,-131071,65535);
        require(!mirror.range_pass&&mirror.screen_z==-float(2*k),"signed mirror of proven cancellation failed");}
    require(chili::ge_float24_add(65535,1,out,error)&&out==65536,"same-sign add carry failed");
    require(chili::ge_float24_add(-65535,-1,out,error)&&out==-65536,"negative same-sign carry failed");
    require(chili::ge_float24_multiply(std::bit_cast<float>(0x3EAAAA00u),3,out,error)&&out<1,"multiply used ideal division/rounding");
    // Direct exact product quantization must not double-round through binary32.
    const float low=std::bit_cast<float>(0x3F80FFFFu),high=std::bit_cast<float>(0x3F800001u);
    require(chili::ge_float24_multiply(low,high,out,error)&&std::bit_cast<unsigned>(out)==0x3F810000,"product truncation boundary mismatch");
    const auto clamped=depth(1,1,65536,0,true);require(clamped.range_pass&&clamped.clamped&&clamped.depth==65535,"high clamp mismatch");
    const auto low_clamped=depth(-1,1,65536,0,true);require(low_clamped.range_pass&&low_clamped.clamped&&low_clamped.depth==0,"low clamp mismatch");
    require(!depth(0,1,1,15,false,16).range_pass,"minimum depth rejection mismatch");
    require(!depth(0,1,1,32768,false,0,32767).range_pass,"maximum depth rejection mismatch");
    const chili::GeDepthSample sentinel{11,22,33,44,true,true};auto sample=sentinel;
    for(float w:{0.0f,2.0f,-1.0f,1.25f,std::numeric_limits<float>::quiet_NaN()}){
        require(!chili::ge_depth_verified(.5f,w,1,1,0,65535,false,sample,error)&&sample==sentinel,"unverified reciprocal changed sample");}
    for(float bad:{std::numeric_limits<float>::infinity(),std::numeric_limits<float>::quiet_NaN(),std::numeric_limits<float>::denorm_min()}){
        out=999;require(!chili::ge_float24_truncate(bad,out,error)&&out==999,"invalid truncate changed output");
        require(!chili::ge_float24_add(bad,1,out,error)&&out==999,"invalid add changed output");
        require(!chili::ge_float24_multiply(1,bad,out,error)&&out==999,"invalid multiply changed output");
        sample=sentinel;require(!chili::ge_depth_verified(bad,1,1,1,0,65535,false,sample,error)&&sample==sentinel,"invalid clip Z changed sample");}
    out=999;require(!chili::ge_float24_multiply(std::numeric_limits<float>::max(),2,out,error)&&out==999,"overflow product changed output");
    require(!chili::ge_float24_multiply(std::numeric_limits<float>::min(),.5f,out,error)&&out==999,"denormal product changed output");
    sample=sentinel;require(!chili::ge_depth_verified(.5f,1,std::bit_cast<float>(0x3F800001u),1,0,65535,false,sample,error)&&sample==sentinel,"nonregister viewport changed sample");
    require(!chili::ge_depth_verified(.5f,1,1,1,0,65536,false,sample,error)&&sample==sentinel,"invalid range changed sample");
    out=999;require(!chili::ge_float24_projection_z(.5f,std::bit_cast<float>(0x3F800001u),1,out,error)&&out==999,"nonregister projection changed output");
}
int main(){try{hardware_vectors();derived_reciprocal_constraint();arithmetic_and_failures();
    std::cout<<"27 real-PSP depth vectors, signed cancellation, unique W=3 endpoint and atomic failure fixtures passed\n";
}catch(const std::exception &e){std::cerr<<e.what()<<'\n';return 1;}}
